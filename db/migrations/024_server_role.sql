-- تفکیک سرور اختصاصی از سرور پایش
--
-- سرورهای پایش — لنگرها و دیدبان‌ها — موجودی واقعی نیستند: مشتری ندارند،
-- ترافیکشان ناچیز است، و در فهرست سرورهای اختصاصی فقط نویز می‌سازند.
-- تا حالا کاملا پنهان بودند که برعکس هم مشکل داشت: وضعیتشان هیچ‌جا دیده
-- نمی‌شد.
--
-- حالا فهرست سرورها دو بخش دارد و هرکدام جای خودش را دارد.
--
-- تشخیص دو راه دارد و هر دو لازم است:
--   • خودکار: سروری که به‌عنوان لنگر انتخاب شده
--   • دستی: این ستون، برای دیدبان‌ها و هر سرور پشتیبان دیگری که خودکار
--     تشخیص داده نمی‌شود
--
-- اجرا روی نصب موجود:
--   docker compose exec -T postgres psql -U pasargad -d pasargad_monitor < db/migrations/024_server_role.sql

