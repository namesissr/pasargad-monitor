-- فروشگاه عمومی: سفارش پیش از ثبت‌نام
--
-- تا حالا برای سفارش باید اول حساب ساخته می‌شد و ادمین آن را دستی
-- می‌ساخت. یعنی مشتری تازه هیچ راهی نداشت جز تماس گرفتن.
--
-- حالا محصولات بدون ورود دیده می‌شوند و ثبت‌نام **حین سفارش** انجام
-- می‌شود: یک فرم، دو حالت — «حساب دارم» و «حساب ندارم».
--
-- ── چرا کلید جدا برای فروشگاه عمومی ────────────────────────
--
-- shop_enabled فروشگاهِ داخل پرتال را کنترل می‌کند. آن یکی برای
-- مشتری‌هایی است که از قبل حساب دارند و خطری ندارد.
--
-- فروشگاه عمومی فرق دارد: هر کسی از اینترنت می‌تواند حساب بسازد. اگر
-- روزی موج ثبت‌نام بی‌هدف آمد، باید بشود همین یکی را خاموش کرد بدون
-- اینکه مشتری‌های فعلی از خرید بیفتند.
--
-- ── یکتایی شماره و ایمیل مشتری ─────────────────────────────
--
-- ایندکس یکتا روی شماره تلفن مشتری. بدون آن، کسی که دو بار فرم را
-- بفرستد دو مشتری با یک شماره می‌سازد و بعد معلوم نیست سرورش زیر
-- کدام است.
--
-- ایندکس جزئی است (فقط ردیف‌های ناتهی) چون مشتری‌های قدیمی که ادمین
-- دستی ساخته ممکن است شماره نداشته باشند.
--
-- اگر داده فعلی شماره تکراری داشته باشد این مهاجرت **شکست می‌خورد** و
-- همین درست است: باید اول تکلیف آن ردیف‌ها روشن شود. برای پیداکردنشان:
--
--   SELECT phone, count(*) FROM customers
--    WHERE phone IS NOT NULL AND phone <> ''
--    GROUP BY phone HAVING count(*) > 1;
--
-- اجرا روی نصب موجود:
--   docker compose exec -T postgres psql -U pasargad -d pasargad_monitor < db/migrations/041_public_store.sql

BEGIN;

CREATE UNIQUE INDEX IF NOT EXISTS customers_phone_uq
  ON customers (phone) WHERE phone IS NOT NULL AND phone <> '';

-- ایمیل یکتا نیست چون چند نفر در یک شرکت ممکن است یک ایمیل بدهند، و
-- شماره تلفن است که کلید واقعی هویت در ایران است.
CREATE INDEX IF NOT EXISTS customers_email_idx
  ON customers (lower(email)) WHERE email IS NOT NULL AND email <> '';

-- مشتری‌ای که خودش ثبت‌نام کرده، از مشتری‌ای که ادمین ساخته جدا شناخته
-- می‌شود. برای پیگیری و برای اینکه ادمین بداند کدام حساب هنوز تأیید
-- انسانی نشده.
ALTER TABLE customers ADD COLUMN IF NOT EXISTS signup_source TEXT;

COMMENT ON COLUMN customers.signup_source IS
  'store یعنی خودش از فروشگاه عمومی ثبت‌نام کرده؛ تهی یعنی ادمین ساخته';

INSERT INTO settings (key, value) VALUES
  -- فروشگاه عمومی و ثبت‌نام حین سفارش
  ('store_public_enabled', 'true'),
  -- یک جمله بالای فروشگاه؛ خالی یعنی متن پیش‌فرض
  ('store_intro', '')
ON CONFLICT (key) DO NOTHING;

COMMIT;
