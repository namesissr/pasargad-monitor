-- اعمال خودکار هنگام آزادشدن آی‌پی
--
-- تا حالا «اعمال واقعی» فقط دستی بود. یعنی آی‌پی‌ای که آزاد شده بود تا
-- کلیک بعدی ادمین روی لنگر اشغال می‌ماند — گاهی روزها.
--
-- حالا لحظه‌ای که وضعیت یک آی‌پی به «آزاد شد» می‌رود، یک درخواست اعمال
-- برای نودش در صف گذاشته می‌شود و ورکر ظرف حدود بیست ثانیه اجرایش
-- می‌کند. منتظر چرخه بعدی نمی‌ماند.
--
-- vz_auto_apply برای خاموش‌کردن این رفتار است. اگر ترجیح می‌دهید هیچ
-- نوشتنی روی ویژالیزور بدون نظر شما انجام نشود، خاموشش کنید؛ آن‌وقت
-- «اعمال واقعی» دوباره فقط دستی می‌شود.
--
-- فاصله کشف هم به سه ساعت می‌رود. هر ساعت برای موجودی‌ای که کند تغییر
-- می‌کند زیاد است و فقط بار بی‌مورد روی نودها می‌گذارد.
--
-- اجرا روی نصب موجود:
--   docker compose exec -T postgres psql -U pasargad -d pasargad_monitor < db/migrations/020_vz_auto_apply.sql

BEGIN;

INSERT INTO settings (key, value) VALUES ('vz_auto_apply', 'true')
ON CONFLICT (key) DO NOTHING;

UPDATE settings SET value = '3', updated_at = now()
 WHERE key = 'vz_discover_hours' AND value = '1';

COMMIT;
