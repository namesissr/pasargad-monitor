-- آی‌پی قفل‌شده در ویژالیزور
--
-- قفل‌کردن یک آدرس در ویژالیزور یعنی ادمین عمداً کنارش گذاشته. مسیر
-- اعمال این را رعایت می‌کرد و هرگز آدرس قفل‌شده را به لنگر نمی‌چسباند،
-- ولی کشف واردش می‌کرد و تحت پایش می‌برد — ناسازگاری بین دو بخش.
--
-- نتیجه‌اش این بود: آدرس قفل‌شده در فهرست پایش می‌نشست، هرگز تخصیص
-- نمی‌یافت، و برای همیشه «روت نشده» گزارش می‌شد بدون اینکه علتش معلوم
-- باشد.
--
-- ستون vz_locked وضعیت واقعی را نگه می‌دارد تا در پنل دیده شود. ردیف‌ها
-- خودکار حذف نمی‌شوند: ممکن است یادداشت یا نام مشتری داشته باشند. کشف
-- بعدی فقط تیک پایششان را برمی‌دارد.
--
-- اجرا روی نصب موجود:
--   docker compose exec -T postgres psql -U pasargad -d pasargad_monitor < db/migrations/019_vz_locked.sql

BEGIN;

ALTER TABLE ip_addresses ADD COLUMN IF NOT EXISTS vz_locked BOOLEAN NOT NULL DEFAULT FALSE;

COMMIT;
