-- پیوند نود ویژالیزور با سرور لنگر در پنل
--
-- شکافی که این مهاجرت پر می‌کند: تخصیص آی‌پی در ویژالیزور و بایند آن
-- داخل خود وی‌پی‌اس دو کار متفاوت‌اند و هر دو لازم‌اند.
--
--   تخصیص در ویژالیزور  →  قواعد ضدجعل اجازه عبور می‌دهند
--   بایند داخل مهمان    →  آدرس روی کارت شبکه می‌نشیند و جواب می‌دهد
--
-- بدون دومی، بسته به سرور می‌رسد ولی کسی جواب نمی‌دهد و آی‌پی برای همیشه
-- «روت نشده» گزارش می‌شود — یعنی چرخه هرگز کامل نمی‌شود.
--
-- پس هر نود باید بداند وی‌پی‌اس لنگرش کدام رکورد «سرور» در پنل است، تا
-- ایجنت لنگر (pasargad-bind) که روی همان وی‌پی‌اس نصب است فهرستش را
-- بگیرد.
--
-- auto_watch_free: آی‌پی آزاد تازه‌کشف‌شده خودکار تحت پایش برود یا نه.
-- روشن است چون کل هدف همین بود؛ ولی اگر مخزنی هزاران آدرس آزاد دارد و
-- نمی‌خواهید همه پایش شوند، برای آن نود خاموشش کنید.
--
-- اجرا روی نصب موجود:
--   docker compose exec -T postgres psql -U pasargad -d pasargad_monitor < db/migrations/016_vz_bind_link.sql

BEGIN;

ALTER TABLE vz_nodes ADD COLUMN IF NOT EXISTS bind_server_id INT REFERENCES servers(id) ON DELETE SET NULL;
ALTER TABLE vz_nodes ADD COLUMN IF NOT EXISTS auto_watch_free BOOLEAN NOT NULL DEFAULT TRUE;

COMMIT;
