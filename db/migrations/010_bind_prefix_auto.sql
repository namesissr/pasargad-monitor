-- پرفیکس بایند خودکار از ساب‌نت
--
-- مهاجرت ۰۰۷ پیش‌فرض را ۳۲ گذاشت با این استدلال که کرنل با arp_ignore=0 به
-- ARP هر آدرس محلی جواب می‌دهد، پس /32 کافی است و ماسک واقعی یک مسیر متصل
-- تکراری می‌سازد.
--
-- در عمل کار نکرد. آدرس ۹۵٫۳۸٫۱۰۱٫۱۳۱ با /۳۲ روی سروری با آدرس اصلی
-- ۹۵٫۳۸٫۱۰۱٫۱۸۰/۲۴ نشست ولی از داخل ایران هم پینگ نداد.
--
-- تفاوت واقعی: با ماسک درست، آدرس یک «secondary» از همان ساب‌نت متصل
-- می‌شود و کرنل مثل آدرس اصلی با آن رفتار می‌کند. با /۳۲ آدرس یک شبکه
-- مستقل تک‌عضوی است — آگهی ARP و انتخاب آدرس مبدأ یکسان نیست و
-- تجهیزات بالادست آن را نمی‌بینند.
--
-- ولی /۲۴ ثابت هم غلط است: اگر آدرس از بلوک دیگری باشد، ماسک اشتباه یک
-- مسیر متصل جعلی می‌سازد و می‌تواند روتینگ سرور را خراب کند.
--
-- قاعده درست: پرفیکس از ساب‌نت ثبت‌شده همان آی‌پی می‌آید. NULL یعنی
-- خودکار. اگر ساب‌نتی ثبت نشده باشد، ایجنت به ۳۲ برمی‌گردد.
--
-- اجرا روی نصب موجود:
--   docker compose exec -T postgres psql -U pasargad -d pasargad_monitor < db/migrations/010_bind_prefix_auto.sql

BEGIN;

ALTER TABLE ip_addresses ALTER COLUMN bind_prefix DROP NOT NULL;
ALTER TABLE ip_addresses ALTER COLUMN bind_prefix DROP DEFAULT;

-- رکوردهای موجودی که پرفیکس دستی نگرفته‌اند به حالت خودکار برمی‌گردند.
-- ۳۲ پیش‌فرض قبلی بود، نه انتخاب کاربر — پس تشخیصشان از هم ممکن نیست و
-- خودکار برای هر دو درست‌تر است.
UPDATE ip_addresses SET bind_prefix = NULL WHERE bind_prefix = 32;

COMMIT;
