-- وضعیت اولیه ترافیک — مهاجرت مشتری موجود به پنل
--
-- مشتری‌ای که پیش از راه‌اندازی پنل ترافیک خریده و بخشی را مصرف کرده،
-- باید بتواند همان وضعیت را در پنل ببیند. خرید با ردیف عادی
-- traffic_topups ثبت می‌شود، ولی مصرف گذشته جایی برای نشستن نداشت:
--
--   moجودی = مجموع خریدها − مصرف اندازه‌گیری‌شده
--
-- و مصرف اندازه‌گیری‌شده برای سروری که تازه اضافه شده صفر است.
--
-- **چرا ثبت دستی ترافیک (backfill) راه درستی نبود:** آن ابزار مجموع را
-- روزبه‌روز پخش می‌کند و ردیف روزانه می‌سازد. برای مشتری‌ای که دو سال
-- مصرف دارد، نتیجه‌اش هفتصد ردیف ساختگی و یک خط صاف در نمودار است که
-- هیچ‌وقت اتفاق نیفتاده. عددی که می‌دانیم مجموع است، پس مجموع ذخیره
-- می‌شود.
--
--   مصرف = traffic_used_before_gb + اندازه‌گیری از traffic_counted_from
--
-- لاگ ترافیک دست‌نخورده می‌ماند و فقط چیزی را نشان می‌دهد که واقعا
-- اندازه گرفته شده.
--
-- اجرا روی نصب موجود:
--   docker compose exec -T postgres psql -U pasargad -d pasargad_monitor < db/migrations/033_opening_usage.sql

BEGIN;

ALTER TABLE servers
  ADD COLUMN IF NOT EXISTS traffic_used_before_gb NUMERIC(14, 2) NOT NULL DEFAULT 0;

COMMENT ON COLUMN servers.traffic_used_before_gb IS
  'مصرفی که پیش از شروع اندازه‌گیری پنل انجام شده؛ به مصرف اندازه‌گیری‌شده اضافه می‌شود';

COMMIT;
