#!/bin/sh
# بررسی تایپ پیش از بیلد.
#
# چرا جدا از بیلد: «next build» اول کامپایل می‌کند و بعد تایپ را بررسی —
# یعنی خطای تایپ بعد از یک دقیقه‌ونیم معلوم می‌شود. این بار اول چند دقیقه
# طول می‌کشد و بعدش حدود بیست ثانیه.
#
# «scripts/check-code.py» جای این را نمی‌گیرد: آن الگوهای شناخته‌شده را
# می‌گیرد، این خود کامپایلر است.
#
# سه درسی که نسخه اول این اسکریپت با آن‌ها شکست:
#
#   ۱. این پروژه فایل قفل ندارد، پس «npm ci» شکست می‌خورد. همان شرطی که
#      داکرفایل‌ها دارند اینجا هم لازم است.
#   ۲. خطای نصب بلعیده می‌شد. حالا «set -e» داخل خود کانتینر هم هست.
#   ۳. «npx tsc» وقتی تایپ‌اسکریپت محلی نباشد می‌رود بسته‌ای به نام tsc از
#      اینترنت می‌گیرد که ربطی به تایپ‌اسکریپت ندارد و پیام گمراه‌کننده
#      می‌دهد. حالا مستقیم از node_modules صدا زده می‌شود.
#
# وابستگی‌ها در یک والیوم نام‌دار کش می‌شوند تا هر بار دوباره نصب نشوند.
#
# اجرا:  sh scripts/typecheck.sh
set -e
cd "$(dirname "$0")/.."

docker run --rm   -v "$PWD:/app"   -v pasargad_typecheck_modules:/app/node_modules   -w /app node:20-alpine sh -euc '
    if [ ! -x node_modules/.bin/tsc ]; then
      echo "نصب وابستگی‌ها (فقط بار اول)…"
      if [ -f package-lock.json ]; then npm ci; else npm install; fi
    fi
    ./node_modules/.bin/tsc --noEmit
  '

echo "تایپ‌ها سالم‌اند."
